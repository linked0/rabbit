// 형제 저장소(~/work/verex)의 설계 문서를 rabbit 안으로 복사한다 (jay, 2026-08-17).
//
// 왜 필요한가: docs/index.html 의 Current Projects 는 Verex 의 Feature Designs / Current Plan
// 카드를 docs/html/projects/verex/** 로 건다. 그런데 generate-docs-html.mjs 는 REPO_ROOT 안의
// .md 만 순회하므로, rabbit 안에 원본이 없으면 그 HTML 을 다시 만들 수가 없다. 실제로 그 미러는
// 2026-08-01 에 커밋된 스냅샷 상태로 멈춰 있었고 — verex 에 새 문서를 추가해도 rabbit 쪽 카드는
// 옛 내용을 계속 보여줬다. 원인은 "생성이 안 된 것"이 아니라 "생성할 원본이 없었던 것"이다.
//
// 그래서 이 스크립트가 원본을 rabbit/projects/verex/ 로 가져오고, 변환은 기존 생성기가 그대로
// 맡는다 — 출력 경로 규칙(docs/html/ + REPO_ROOT 기준 상대경로)이 기존 미러 경로와 정확히
// 일치하므로 생성기는 손댈 필요가 없다.
//
// 마크다운 원본도 함께 커밋한다: 어느 시점의 verex 를 복사한 것인지 rabbit 의 git 이 직접
// 기록하게 하려는 것. 같은 이유로 SOURCE.txt 에 verex 의 커밋 해시를 남긴다.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const VEREX_ROOT = path.resolve(REPO_ROOT, '..', 'verex');
const DEST_ROOT = path.join(REPO_ROOT, 'projects', 'verex');

// 미러할 범위 — Current Projects 카드가 거는 두 갈래만. verex 저장소 전체가 아니라
// 설계 문서만 가져온다 (docs/history 는 이미 docs/history/ 로 따로 복사되는 경로가 있다).
const SUBDIRS = ['docs/features', 'docs/tasks'];

function syncDir(rel) {
  const src = path.join(VEREX_ROOT, rel);
  const dest = path.join(DEST_ROOT, rel);
  if (!fs.existsSync(src)) return 0;
  fs.mkdirSync(dest, { recursive: true });

  let n = 0;
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (!entry.isFile() || !/\.md$/i.test(entry.name)) continue;
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    const body = fs.readFileSync(from);
    // 내용은 한 글자도 고치지 않는다 — 헤더를 덧붙이면 문서 간 상대 링크와 앵커가 어긋난다.
    if (fs.existsSync(to) && fs.readFileSync(to).equals(body)) continue;
    fs.writeFileSync(to, body);
    n += 1;
  }
  return n;
}

function verexHead() {
  try {
    return execFileSync('git', ['-C', VEREX_ROOT, 'rev-parse', 'HEAD'], {
      encoding: 'utf8',
    }).trim();
  } catch {
    return 'unknown';
  }
}

// 형제 저장소가 없는 머신에서도 docs:html 이 깨지지 않게 조용히 통과시킨다.
if (!fs.existsSync(VEREX_ROOT)) {
  console.log(`verex-sync: skipped — ${path.relative(REPO_ROOT, VEREX_ROOT)} not found`);
  process.exit(0);
}

let updated = 0;
for (const rel of SUBDIRS) updated += syncDir(rel);

fs.mkdirSync(DEST_ROOT, { recursive: true });
fs.writeFileSync(
  path.join(DEST_ROOT, 'SOURCE.txt'),
  // .txt 인 이유: .md 였다면 생성기가 이 파일까지 HTML 로 만들어 미러에 군더더기를 남긴다.
  [
    'Mirror of ~/work/verex design docs — generated by scripts/sync-verex-docs.mjs.',
    'Do not edit here; edit in the verex repo and re-run `pnpm docs:html`.',
    '',
    `verex commit: ${verexHead()}`,
    `mirrored paths: ${SUBDIRS.join(', ')} (*.md only)`,
    '',
  ].join('\n'),
);

console.log(`verex-sync: ${updated} file(s) updated under projects/verex/`);
