#!/usr/bin/env node
// 형제 저장소(~/work/jayverse-defi)의 DeFi 스터디 UI(web/src)를 rabbit 안으로 복사한다 —
// scripts/sync-verex-sdk.mjs 와 같은 패턴, 같은 이유. Docker 빌드 컨텍스트는 rabbit
// 하나뿐이라 컨테이너 안에 ../jayverse-defi 가 없다. 이 사본은 **생성물**이다: 손대지
// 않고, 한 명령으로 다시 만들며, 어느 커밋에서 왔는지 SOURCE.txt 에 남는다.
// 원본 규칙 (jayverse-defi README): UI 는 저쪽에서 *작성*하고 rabbit 은 *서빙*만 한다 —
// rabbit 쪽에서 lib/jayverse-defi-ui 를 고치지 말 것.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const SRC_REPO = path.resolve(REPO_ROOT, '..', 'jayverse-defi');
const SRC = path.join(SRC_REPO, 'web', 'src');
const DEST = path.join(REPO_ROOT, 'lib', 'jayverse-defi-ui');

if (!fs.existsSync(SRC)) {
  console.error(`sync-defi-ui: source not found: ${SRC}`);
  process.exit(1);
}

fs.rmSync(DEST, { recursive: true, force: true });
fs.mkdirSync(DEST, { recursive: true });
for (const f of fs.readdirSync(SRC)) {
  fs.copyFileSync(path.join(SRC, f), path.join(DEST, f));
}

// addresses.json → addresses.ts (JSON import 설정과 무관하게 동작하도록 TS 로 생성)
const addresses = JSON.parse(fs.readFileSync(path.join(SRC_REPO, 'addresses.json'), 'utf8'));
fs.writeFileSync(
  path.join(DEST, 'addresses.ts'),
  `// generated by scripts/sync-defi-ui.mjs — do not edit (source: jayverse-defi/addresses.json)\n` +
    `export const DEFI_ADDRESSES = ${JSON.stringify(addresses, null, 2)} as const;\n`
);

const commit = execSync('git rev-parse --short HEAD', { cwd: SRC_REPO }).toString().trim();
fs.writeFileSync(
  path.join(DEST, 'SOURCE.txt'),
  `jayverse-defi web/src @ ${commit}\nsynced ${new Date().toISOString()} by scripts/sync-defi-ui.mjs\nDo not edit by hand — re-run the script instead.\n`
);
console.log(`sync-defi-ui: ${fs.readdirSync(DEST).length} files → lib/jayverse-defi-ui (source @ ${commit})`);
