#!/usr/bin/env node
// 형제 저장소(~/work/verex)의 `@verex/sdk` **빌드 산출물**을 rabbit 안으로 복사한다
// (jay, 2026-08-28). `scripts/sync-verex-docs.mjs` 와 같은 패턴이고, 같은 이유로
// verex 의 커밋 해시를 SOURCE.txt 에 남긴다.
//
// **왜 필요한가.** package.json 이 `file:../verex/packages/sdk` 를 가리키고 있었고,
// Docker 빌드 컨텍스트는 rabbit 하나뿐이라 컨테이너 안에 `../verex` 가 없다.
// `pnpm install --frozen-lockfile` 이 여기서 죽는다:
//
//   [ENOENT] no such file or directory, scandir '/verex/packages/sdk'
//
// 그래서 rabbit 은 Phase 1(e95f8f4) 이후로 **배포 불가 상태**였고, 아무도 배포하지
// 않아서 아무도 몰랐다 — 마지막 성공 빌드가 2026-08-12 다.
//
// **계획서 O1 의 "복사하지 말 것"과 충돌하지 않는 이유.** O1 이 거부한 것은 **손으로
// 관리하는 사본**이다: 서명 대상이 12개 필드에 대한 EIP-712 해시라, 한 글자만 어긋나도
// *틀린 메시지에 대한 유효한 서명*이 나오고 에러는 구조체를 언급하지 않는다. 이 사본은
// **생성물**이다 — 손대지 않고, 한 명령으로 다시 만들며, 어느 커밋에서 왔는지가
// SOURCE.txt 와 git diff 에 드러난다. O1 의 진짜 답(npm 퍼블리시)이 오면 이 폴더를
// 지우고 package.json 의 한 줄을 버전으로 바꾸면 끝이다.
//
// **src 가 아니라 dist 를 복사하는 이유.** 패키지의 `main` 이 이미 `dist/index.js` 이고,
// 런타임 의존성은 `viem` 하나인데 rabbit 에 이미 있다. 컨테이너 안에서 TypeScript 를
// 빌드할 필요가 없다.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const SDK_SRC = path.resolve(REPO_ROOT, "..", "verex", "packages", "sdk");
const DEST = path.join(REPO_ROOT, "vendor", "verex-sdk");

if (!fs.existsSync(SDK_SRC)) {
  console.error(`✗ ${SDK_SRC} 가 없습니다. verex 저장소가 rabbit 과 같은 부모 폴더에 있어야 합니다.`);
  process.exit(1);
}
if (!fs.existsSync(path.join(SDK_SRC, "dist", "index.js"))) {
  console.error(
    `✗ ${SDK_SRC}/dist 가 없습니다. 먼저 빌드하세요:\n` +
      `    cd ../verex && pnpm --filter @verex/sdk build`,
  );
  process.exit(1);
}

// 통째로 다시 만든다. 부분 갱신은 verex 에서 **삭제된** 파일이 사본에 남는 실패를
// 만들고, 그 파일은 아무도 안 읽는 채로 diff 만 어지럽힌다.
fs.rmSync(DEST, { recursive: true, force: true });
fs.mkdirSync(DEST, { recursive: true });
fs.cpSync(path.join(SDK_SRC, "dist"), path.join(DEST, "dist"), { recursive: true });

// package.json 은 그대로 쓰지 않는다 — devDependencies(typescript, vitest)와 빌드
// 스크립트는 사본에 의미가 없고, 설치할 때 받아 올 이유도 없다. 런타임에 실제로
// 필요한 것만 남긴다.
const upstream = JSON.parse(fs.readFileSync(path.join(SDK_SRC, "package.json"), "utf8"));
fs.writeFileSync(
  path.join(DEST, "package.json"),
  JSON.stringify(
    {
      name: upstream.name,
      version: upstream.version,
      private: true,
      main: upstream.main,
      types: upstream.types,
      dependencies: upstream.dependencies,
    },
    null,
    2,
  ) + "\n",
);

let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", path.resolve(REPO_ROOT, "..", "verex"), "rev-parse", "HEAD"], {
    encoding: "utf8",
  }).trim();
} catch {
  // verex 가 git 저장소가 아니어도 복사 자체는 유효하다 — 다만 출처를 모른다고 적는다.
}
fs.writeFileSync(
  path.join(DEST, "SOURCE.txt"),
  `generated by scripts/sync-verex-sdk.mjs — do not edit by hand\n` +
    `source: ../verex/packages/sdk (dist only)\n` +
    `verex commit: ${commit}\n` +
    `run \`pnpm sdk:sync-verex\` after changing the SDK in verex\n`,
);

const files = fs.readdirSync(path.join(DEST, "dist")).length;
console.log(`✓ vendor/verex-sdk ← ../verex/packages/sdk/dist (${files} entries)`);
console.log(`  verex commit ${commit.slice(0, 10)}`);
